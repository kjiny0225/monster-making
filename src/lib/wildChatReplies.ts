function pickWildChatResponse(responses: string[], playerMonsterName?: string) {
  const template = responses[Math.floor(Math.random() * responses.length)];

  if (!playerMonsterName) {
    return template.replaceAll("{name}", "친구");
  }

  return template.replaceAll("{name}", playerMonsterName);
}

export function getWildMonsterReply(message: string, playerMonsterName?: string) {
  const normalized = message.trim().toLowerCase();
  let bestRule: WildChatReplyRule | null = null;
  let bestScore = 0;

  for (const rule of WILD_CHAT_REPLY_RULES) {
    let score = 0;

    for (const keyword of rule.keywords) {
      if (normalized.includes(keyword)) {
        score += Math.max(keyword.length, 2);
      }
    }

    if (score > bestScore) {
      bestScore = score;
      bestRule = rule;
    }
  }

  if (bestRule) {
    return pickWildChatResponse(bestRule.responses, playerMonsterName);
  }

  return pickWildChatResponse(WILD_CHAT_FALLBACK_REPLIES, playerMonsterName);
}
